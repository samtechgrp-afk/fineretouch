"""Write the browser / Python healing parity fixture (apps/web/src/engine/__fixtures__/heal-parity.json).

The input is a crop of a Skin Perfection result with repairs in it (a synthetic scene, so no
person's photo is stored), and four strokes across those repairs. The expected output is
engines/local.apply_heal_strokes on that 8-bit input. tests/test_heal_parity.py checks the Python
side against it, apps/web/src/engine/heal.parity.test.ts the browser side.

    cd services/ai && python -m scripts.heal_parity_fixture
"""

from __future__ import annotations

import base64
import json
import zlib
from pathlib import Path

import numpy as np

FIXTURE = Path(__file__).resolve().parents[3] / "apps" / "web" / "src" / "engine" / "__fixtures__" / "heal-parity.json"
SIZE = 160


def pack(a: np.ndarray) -> str:
    return base64.b64encode(zlib.compress(np.ascontiguousarray(a, np.uint8).tobytes(), 9)).decode("ascii")


def unpack(s: str, h: int, w: int) -> np.ndarray:
    return np.frombuffer(zlib.decompress(base64.b64decode(s)), np.uint8).reshape(h, w, 3)


def python_heal(img: np.ndarray, strokes: list[dict]) -> np.ndarray:
    from app.engines.local import apply_heal_strokes
    from app.schemas import HealStroke

    out = apply_heal_strokes(img.astype(np.float32) / 255.0, [HealStroke(**s) for s in strokes])
    return (np.clip(out, 0.0, 1.0) * 255.0 + 0.5).astype(np.uint8)


def build() -> dict:
    from app.pipeline import render
    from app.schemas import Adjustments, SkinPerfectionSettings
    from tests.perfection_fixtures import make_scene, oval_face

    img, _, _ = make_scene(size=700, tone="IV", seed=12, with_natural=False)
    rgb8 = (img * 255 + 0.5).astype(np.uint8)
    rep: list = []
    perfected = np.asarray(render(rgb8, Adjustments(skinPerfection=SkinPerfectionSettings(enabled=True)), [oval_face(700, 700)], report=rep))
    # The crop with the most corrected marks in it.
    marks = [m for m in rep[0].marks if m.status == "corrected"]
    best = max(((x, y) for y in range(100, 540, 20) for x in range(100, 540, 20)),
               key=lambda p: sum(p[0] + 20 <= m.x < p[0] + SIZE - 20 and p[1] + 20 <= m.y < p[1] + SIZE - 20 for m in marks))
    x0, y0 = best
    crop = perfected[y0:y0 + SIZE, x0:x0 + SIZE].copy()
    inside = sorted([m for m in marks if x0 + 20 <= m.x < x0 + SIZE - 20 and y0 + 20 <= m.y < y0 + SIZE - 20], key=lambda m: -m.r)
    assert len(inside) >= 2, "need repairs in the crop"
    a, b = inside[0], inside[1]
    n = lambda v: round(float(v) / SIZE, 6)
    ax, ay, bx, by = a.x - x0, a.y - y0, b.x - x0, b.y - y0
    strokes = [
        # Heal across the largest repair, source 31.5 px to the right (bilinear sampling).
        {"mode": "heal", "size": n(3.0 * a.r + 2), "hardness": 50, "opacity": 100, "offset": [n(31.5), 0.0],
             "points": [n(ax - 2 * a.r), n(ay), n(ax + 2 * a.r), n(ay)]},
        # Clone over the second repair at 70% opacity, a hard tip, source up and left.
        {"mode": "clone", "size": n(2.5 * b.r + 2), "hardness": 80, "opacity": 70, "offset": [n(-17.25), n(-22.75)],
             "points": [n(bx), n(by)]},
        # A soft three-point heal stroke crossing both repairs.
        {"mode": "heal", "size": n(5.0), "hardness": 0, "opacity": 100, "offset": [n(0.0), n(28.0)],
             "points": [n(ax), n(ay), n((ax + bx) / 2 + 6), n((ay + by) / 2 - 4), n(bx), n(by)]},
        # A heal stroke touching the crop edge (edge clamping in the source).
        {"mode": "heal", "size": n(6.0), "hardness": 40, "opacity": 90, "offset": [n(12.0), n(-9.5)],
             "points": [n(4.0), n(SIZE - 30.0), n(30.0), n(SIZE - 4.0)]},
    ]
    expected = python_heal(crop, strokes)
    return {
        "note": "Generated by services/ai/scripts/heal_parity_fixture.py. A crop of a Skin Perfection result "
                f"(synthetic scene, crop at x={x0}, y={y0}) with repairs under the strokes.",
        "width": SIZE, "height": SIZE, "strokes": strokes,
        "input": pack(crop), "expected": pack(expected),
        "repairs": [{"x": round(m.x - x0, 2), "y": round(m.y - y0, 2), "r": round(m.r, 2)} for m in (a, b)],
    }


if __name__ == "__main__":
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(build(), indent=1))
    print("wrote", FIXTURE)
